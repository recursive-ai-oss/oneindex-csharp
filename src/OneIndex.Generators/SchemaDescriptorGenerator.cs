using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace OneIndex.Generators;

/// <summary>
/// For every class that has properties carrying OneIndex attributes, emits <c>OneIndex.Generated.&lt;Type&gt;SchemaDescriptor</c>:
/// the field names, their kinds and the identifier field, in declaration order. This is the seed of the full source-generated
/// mapping; it proves the generator ships inside the package and runs at build time with no runtime reflection.
/// </summary>
[Generator]
public sealed class SchemaDescriptorGenerator : IIncrementalGenerator
{
    private const string AttributeNamespace = "OneIndex";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // The pipeline's values are (hint name, source text) strings, which compare by value, so unchanged classes are not regenerated.
        IncrementalValuesProvider<(string HintName, string Source)> classes = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax c && c.Members.OfType<PropertyDeclarationSyntax>().Any(p => p.AttributeLists.Count > 0),
                static (ctx, ct) => Describe(ctx, ct))
            .Where(static x => x.Source.Length > 0);

        context.RegisterSourceOutput(classes, static (spc, item) => spc.AddSource(item.HintName, item.Source));
    }

    private static (string HintName, string Source) Describe(GeneratorSyntaxContext ctx, CancellationToken ct)
    {
        var declaration = (ClassDeclarationSyntax)ctx.Node;
        if (ctx.SemanticModel.GetDeclaredSymbol(declaration, ct) is not INamedTypeSymbol type)
        {
            return (string.Empty, string.Empty);
        }

        var names = new List<string>();
        var kinds = new List<string>();
        string? id = null;
        foreach (IPropertySymbol property in type.GetMembers().OfType<IPropertySymbol>())
        {
            string? kind = null;
            var flags = new List<string>();
            foreach (AttributeData attribute in property.GetAttributes())
            {
                INamedTypeSymbol? attributeClass = attribute.AttributeClass;
                if (attributeClass is null || attributeClass.ContainingNamespace.ToDisplayString() != AttributeNamespace)
                {
                    continue;
                }

                switch (attributeClass.Name)
                {
                    case "SearchIdAttribute":
                        kind = "id";
                        id = property.Name;
                        break;
                    case "FullTextAttribute":
                        kind = "text";
                        break;
                    case "KeywordAttribute":
                        kind = "keyword";
                        break;
                    case "DynamicAttribute":
                        kind = "json";
                        break;
                    case "VectorAttribute":
                        kind = "vector";
                        break;
                    case "FilterableAttribute":
                        flags.Add("filterable");
                        break;
                    case "SortableAttribute":
                        flags.Add("sortable");
                        break;
                    case "FacetAttribute":
                        flags.Add("facet");
                        break;
                }
            }

            if (kind is null && flags.Count == 0)
            {
                continue;
            }

            names.Add(property.Name);
            kinds.Add((kind ?? "value") + string.Concat(flags.Select(f => "," + f)));
        }

        if (names.Count == 0)
        {
            return (string.Empty, string.Empty);
        }

        string ns = type.ContainingNamespace.IsGlobalNamespace ? string.Empty : type.ContainingNamespace.ToDisplayString();
        string safe = (ns.Length == 0 ? type.Name : ns.Replace('.', '_') + "_" + type.Name);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace OneIndex.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>The searchable shape of <c>" + type.ToDisplayString() + "</c>, from its OneIndex attributes.</summary>");
        sb.AppendLine("    internal static class " + safe + "SchemaDescriptor");
        sb.AppendLine("    {");
        sb.AppendLine("        public const string TypeName = \"" + type.ToDisplayString() + "\";");
        sb.AppendLine("        public const string? IdField = " + (id is null ? "null" : "\"" + id + "\"") + ";");
        sb.AppendLine("        public static readonly string[] FieldNames = { " + string.Join(", ", names.Select(n => "\"" + n + "\"")) + " };");
        sb.AppendLine("        public static readonly string[] FieldKinds = { " + string.Join(", ", kinds.Select(k => "\"" + k + "\"")) + " };");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return (safe + ".SchemaDescriptor.g.cs", sb.ToString());
    }
}
