using System.Diagnostics.CodeAnalysis;
using System.Reflection;
using Microsoft.Extensions.VectorData;

namespace OneIndex.VectorData;

internal enum PropKind
{
    Key,
    Data,
    Vector,
}

/// <summary>One property of a record class: what it is to the store and how to read and write it.</summary>
internal sealed class PropModel(string name, PropertyInfo info, PropKind kind)
{
    public string Name { get; } = name;

    public PropertyInfo Info { get; } = info;

    public PropKind Kind { get; } = kind;

    public Type Type => Info.PropertyType;

    public bool IsIndexed { get; init; }

    public bool IsFullTextIndexed { get; init; }

    public bool IsAutoGenerated { get; init; }

    public int Dimensions { get; init; }

    public string? DistanceFunction { get; init; }

    public object? Get(object record) => Info.GetValue(record);

    public void Set(object record, object? value) => Info.SetValue(record, value);
}

/// <summary>The properties of a record class, found from the abstraction's attributes or from a collection definition.</summary>
[RequiresUnreferencedCode("Records are read and written through reflection over their properties.")]
[RequiresDynamicCode("Records are read and written through reflection over their properties.")]
internal sealed class RecordModel
{
    private RecordModel(PropModel key, List<PropModel> data, List<PropModel> vectors)
    {
        KeyProperty = key;
        DataProperties = data;
        VectorProperties = vectors;
    }

    public PropModel KeyProperty { get; }

    public List<PropModel> DataProperties { get; }

    public List<PropModel> VectorProperties { get; }

    public IEnumerable<PropModel> Properties => DataProperties.Prepend(KeyProperty).Concat(VectorProperties);

    public static T Create<T>()
        where T : class
        => Activator.CreateInstance<T>();

    public static RecordModel Build(Type record, VectorStoreCollectionDefinition? definition)
    {
        PropModel? key = null;
        var data = new List<PropModel>();
        var vectors = new List<PropModel>();
        if (definition is not null)
        {
            foreach (VectorStoreProperty p in definition.Properties)
            {
                PropertyInfo info = record.GetProperty(p.Name, BindingFlags.Public | BindingFlags.Instance)
                    ?? throw new InvalidOperationException($"The definition names a property '{p.Name}' that {record.Name} does not have.");
                switch (p)
                {
                    case VectorStoreKeyProperty k:
                        key = Single(key, new PropModel(p.Name, info, PropKind.Key) { IsAutoGenerated = k.IsAutoGenerated ?? false }, record);
                        break;
                    case VectorStoreDataProperty d:
                        data.Add(new PropModel(p.Name, info, PropKind.Data) { IsIndexed = d.IsIndexed, IsFullTextIndexed = d.IsFullTextIndexed });
                        break;
                    case VectorStoreVectorProperty v:
                        vectors.Add(new PropModel(p.Name, info, PropKind.Vector) { Dimensions = v.Dimensions, DistanceFunction = v.DistanceFunction });
                        break;
                }
            }
        }
        else
        {
            foreach (PropertyInfo info in record.GetProperties(BindingFlags.Public | BindingFlags.Instance))
            {
                if (info.GetCustomAttribute<VectorStoreKeyAttribute>() is { } k)
                {
                    key = Single(key, new PropModel(info.Name, info, PropKind.Key) { IsAutoGenerated = k.IsAutoGenerated }, record);
                }
                else if (info.GetCustomAttribute<VectorStoreDataAttribute>() is { } d)
                {
                    data.Add(new PropModel(info.Name, info, PropKind.Data) { IsIndexed = d.IsIndexed, IsFullTextIndexed = d.IsFullTextIndexed });
                }
                else if (info.GetCustomAttribute<VectorStoreVectorAttribute>() is { } v)
                {
                    vectors.Add(new PropModel(info.Name, info, PropKind.Vector) { Dimensions = v.Dimensions, DistanceFunction = v.DistanceFunction });
                }
            }
        }

        if (key is null)
        {
            throw new InvalidOperationException($"{record.Name} needs exactly one key property (VectorStoreKey).");
        }

        foreach (PropModel v in vectors)
        {
            if (v.Dimensions < 1)
            {
                throw new InvalidOperationException($"The vector property '{v.Name}' needs its Dimensions.");
            }
        }

        // The schema is recorded in the index, so its field order must not depend on reflection order.
        data.Sort(static (a, b) => string.CompareOrdinal(a.Name, b.Name));
        vectors.Sort(static (a, b) => string.CompareOrdinal(a.Name, b.Name));
        return new RecordModel(key, data, vectors);
    }

    private static PropModel Single(PropModel? existing, PropModel next, Type record)
        => existing is null ? next : throw new InvalidOperationException($"{record.Name} has more than one key property.");
}
