using Microsoft.Extensions.VectorData;
using OneIndex.VectorData;

namespace OneIndex.VectorData.Tests;

public sealed class Hotel
{
    [VectorStoreKey]
    public string Id { get; set; } = string.Empty;

    [VectorStoreData(IsIndexed = true)]
    public string City { get; set; } = string.Empty;

    [VectorStoreData(IsFullTextIndexed = true)]
    public string Description { get; set; } = string.Empty;

    [VectorStoreData(IsIndexed = true)]
    public int Rating { get; set; }

    [VectorStoreData(IsIndexed = true)]
    public string[] Tags { get; set; } = [];

    [VectorStoreData]
    public DateTimeOffset Opened { get; set; }

    [VectorStoreVector(4, DistanceFunction = DistanceFunction.CosineSimilarity)]
    public ReadOnlyMemory<float> Embedding { get; set; }
}

public sealed class GuidItem
{
    [VectorStoreKey(IsAutoGenerated = true)]
    public Guid Id { get; set; }

    [VectorStoreData]
    public string Name { get; set; } = string.Empty;

    [VectorStoreVector(2, DistanceFunction = DistanceFunction.EuclideanDistance)]
    public float[]? Position { get; set; }
}

public class ContractTests
{
    private static Hotel Make(string id, string city, string text, int rating, float[] v, params string[] tags)
        => new() { Id = id, City = city, Description = text, Rating = rating, Tags = tags, Opened = new DateTimeOffset(2020, 1, 1, 0, 0, 0, TimeSpan.Zero).AddDays(rating), Embedding = v };

    private static async Task<VectorStoreCollection<string, Hotel>> Seed(OneIndexVectorStore store)
    {
        VectorStoreCollection<string, Hotel> c = store.GetCollection<string, Hotel>("hotels");
        await c.EnsureCollectionExistsAsync();
        await c.UpsertAsync(
        [
            Make("1", "Paris", "quiet boutique hotel near the river", 5, [1, 0, 0, 0], "quiet", "river"),
            Make("2", "Paris", "loud hostel by the station", 2, [0, 1, 0, 0], "loud"),
            Make("3", "Rome", "quiet hotel with a garden", 4, [0.9f, 0.1f, 0, 0], "quiet", "garden"),
            Make("4", "Rome", "business hotel airport shuttle", 3, [0, 0, 1, 0], "business"),
        ]);
        return c;
    }

    [Fact]
    public async Task UpsertGetDeleteRoundTrip()
    {
        using var store = new OneIndexVectorStore();
        VectorStoreCollection<string, Hotel> c = await Seed(store);
        Hotel? h = await c.GetAsync("1");
        Assert.NotNull(h);
        Assert.Equal("Paris", h.City);
        Assert.Equal(5, h.Rating);
        Assert.Equal(["quiet", "river"], h.Tags);
        Assert.Equal(new DateTimeOffset(2020, 1, 6, 0, 0, 0, TimeSpan.Zero), h.Opened);
        Assert.True(h.Embedding.IsEmpty, "vectors are left out unless asked for");
        Hotel? withVector = await c.GetAsync("1", new RecordRetrievalOptions { IncludeVectors = true });
        Assert.Equal([1f, 0, 0, 0], withVector!.Embedding.ToArray());

        h.City = "Lyon";
        await c.UpsertAsync(h);
        Assert.Equal("Lyon", (await c.GetAsync("1"))!.City);
        Assert.Equal(4, await CountAsync(c.GetAsync(r => r.Rating > 0, 10)));

        await c.DeleteAsync("1");
        Assert.Null(await c.GetAsync("1"));
        await c.DeleteAsync("nope");
        var many = new List<Hotel>();
        await foreach (Hotel r in c.GetAsync(["2", "3", "missing"])) { many.Add(r); }
        Assert.Equal(["2", "3"], many.Select(static x => x.Id).Order().ToArray());
    }

    private static async Task<int> CountAsync<T>(IAsyncEnumerable<T> items)
    {
        int n = 0;
        await foreach (T _ in items) { n++; }
        return n;
    }

    [Fact]
    public async Task FilteredGetOrdersAndPages()
    {
        using var store = new OneIndexVectorStore();
        VectorStoreCollection<string, Hotel> c = await Seed(store);
        var options = new FilteredRecordRetrievalOptions<Hotel> { OrderBy = o => o.Descending(static r => r.Rating) };
        var ids = new List<string>();
        await foreach (Hotel r in c.GetAsync(static r => r.City == "Paris" || r.City == "Rome", 3, options)) { ids.Add(r.Id); }
        Assert.Equal(["1", "3", "4"], ids);
        options.Skip = 3;
        ids.Clear();
        await foreach (Hotel r in c.GetAsync(static r => r.Rating >= 0, 3, options)) { ids.Add(r.Id); }
        Assert.Equal(["2"], ids);
        Assert.Equal(1, await CountAsync(c.GetAsync(static r => r.Tags.Contains("garden"), 5)));
    }

    [Fact]
    public async Task VectorSearchRanksFiltersAndScores()
    {
        using var store = new OneIndexVectorStore();
        VectorStoreCollection<string, Hotel> c = await Seed(store);
        var found = new List<VectorSearchResult<Hotel>>();
        await foreach (VectorSearchResult<Hotel> r in c.SearchAsync(new ReadOnlyMemory<float>([1, 0, 0, 0]), 3)) { found.Add(r); }
        Assert.Equal(["1", "3", "2"], found.Select(static x => x.Record.Id).ToArray());
        Assert.Equal(1.0, found[0].Score!.Value, 3);
        Assert.Equal(0.0, found[2].Score!.Value, 3);
        Assert.True(found[0].Record.Embedding.IsEmpty);

        found.Clear();
        await foreach (VectorSearchResult<Hotel> r in c.SearchAsync(new ReadOnlyMemory<float>([1, 0, 0, 0]), 2, new VectorSearchOptions<Hotel> { Filter = static h => h.City == "Rome", IncludeVectors = true })) { found.Add(r); }
        Assert.Equal(["3", "4"], found.Select(static x => x.Record.Id).ToArray());
        Assert.False(found[0].Record.Embedding.IsEmpty);

        found.Clear();
        await foreach (VectorSearchResult<Hotel> r in c.SearchAsync(new ReadOnlyMemory<float>([1, 0, 0, 0]), 4, new VectorSearchOptions<Hotel> { Skip = 1, ScoreThreshold = 0.1 })) { found.Add(r); }
        Assert.Equal(["3"], found.Select(static x => x.Record.Id).ToArray());
    }

    [Fact]
    public async Task HybridSearchFusesKeywordsAndVector()
    {
        using var store = new OneIndexVectorStore();
        VectorStoreCollection<string, Hotel> c = await Seed(store);
        var hybrid = (IKeywordHybridSearchable<Hotel>)c;
        var ids = new List<string>();
        await foreach (VectorSearchResult<Hotel> r in hybrid.HybridSearchAsync(new ReadOnlyMemory<float>([0, 1, 0, 0]), ["quiet", "garden"], 4)) { ids.Add(r.Record.Id); }
        Assert.Contains("3", ids);
        Assert.Contains("2", ids);
        Assert.True(ids.Count >= 3);
    }

    [Fact]
    public async Task GuidKeysAreGeneratedAndDistancesAreDistances()
    {
        using var store = new OneIndexVectorStore();
        VectorStoreCollection<Guid, GuidItem> c = store.GetCollection<Guid, GuidItem>("items");
        await c.EnsureCollectionExistsAsync();
        var a = new GuidItem { Name = "a", Position = [0, 0] };
        var b = new GuidItem { Name = "b", Position = [3, 4] };
        await c.UpsertAsync([a, b]);
        Assert.NotEqual(Guid.Empty, a.Id);
        var found = new List<VectorSearchResult<GuidItem>>();
        await foreach (VectorSearchResult<GuidItem> r in c.SearchAsync(new float[] { 0, 0 }, 2)) { found.Add(r); }
        Assert.Equal(a.Id, found[0].Record.Id);
        Assert.Equal(0.0, found[0].Score!.Value, 4);
        Assert.Equal(5.0, found[1].Score!.Value, 4);
    }

    [Fact]
    public async Task CollectionsPersistAndManage()
    {
        string dir = Path.Combine(Path.GetTempPath(), "oneindex-vd-" + Guid.NewGuid().ToString("N"));
        try
        {
            using (var store = new OneIndexVectorStore(dir))
            {
                VectorStoreCollection<string, Hotel> c = await Seed(store);
                Assert.True(await c.CollectionExistsAsync());
            }

            using (var store = new OneIndexVectorStore(dir))
            {
                VectorStoreCollection<string, Hotel> c = store.GetCollection<string, Hotel>("hotels");
                Assert.Equal("Rome", (await c.GetAsync("4"))!.City);
                var names = new List<string>();
                await foreach (string n in store.ListCollectionNamesAsync()) { names.Add(n); }
                Assert.Equal(["hotels"], names);
                await c.EnsureCollectionDeletedAsync();
                Assert.False(await store.CollectionExistsAsync("hotels"));
                await Assert.ThrowsAsync<VectorStoreException>(() => c.GetAsync("4"));
            }
        }
        finally
        {
            if (Directory.Exists(dir)) { Directory.Delete(dir, true); }
        }
    }

    [Fact]
    public void BadNamesAndRecordsAreRefused()
    {
        using var store = new OneIndexVectorStore();
        Assert.Throws<ArgumentException>(() => store.GetCollection<string, Hotel>("../x"));
        Assert.Throws<NotSupportedException>(() => store.GetDynamicCollection("d", new VectorStoreCollectionDefinition()));
    }
}
