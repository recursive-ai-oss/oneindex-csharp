#!/usr/bin/env python3
"""Generates src/OneIndex/Analysis/StopWordData.g.cs from the stop word lists published by the Snowball project.

    python3 tools/generate-stopwords.py <directory with <language>.txt lists> <output file>

Each list is https://snowballstem.org/algorithms/<language>/stop.txt (comments start with a vertical bar; a line may hold
several words). The generated file records the SHA-256 of every list it was built from. Standard library only.
"""
import hashlib
import sys
from pathlib import Path

# (snowball language name, ISO 639-1 code used by the analyzer names)
LANGUAGES = [
    ("danish", "da"), ("dutch", "nl"), ("english", "en"), ("finnish", "fi"), ("french", "fr"), ("german", "de"),
    ("hungarian", "hu"), ("indonesian", "id"), ("irish", "ga"), ("italian", "it"), ("norwegian", "no"),
    ("portuguese", "pt"), ("russian", "ru"), ("sesotho", "st"), ("spanish", "es"), ("swedish", "sv"),
]


def words(text: str):
    seen = set()
    for line in text.splitlines():
        for w in line.split("|")[0].split():
            seen.add(w)
    # Ordinal order of UTF-16 code units, which is what the binary search in StopWords compares.
    return sorted(seen, key=lambda w: w.encode("utf-16-be"))


def literal(w: str) -> str:
    out = []
    for ch in w:
        if ch in '"\\':
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("\\u%04X" % ord(ch))  # all stop words are in the Basic Multilingual Plane
    return '"' + "".join(out) + '"'


def main() -> None:
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    lines = [
        "// <auto-generated>",
        "// Generated by tools/generate-stopwords.py from the stop word lists published at https://snowballstem.org/algorithms/<language>/stop.txt.",
        "// The Snowball site's content is under the BSD 3-clause licence (https://snowballstem.org/license.html); see THIRD-PARTY-NOTICES.md.",
        "// Source lists (SHA-256):",
    ]
    bodies = []
    for name, code in LANGUAGES:
        data = (src / f"{name}.txt").read_bytes()
        lines.append(f"//   {name}.txt {hashlib.sha256(data).hexdigest()}")
        ws = words(data.decode("utf-8"))
        bodies.append((name, code, ws))
    lines += ["// </auto-generated>", "#nullable enable", "", "namespace OneIndex.Analysis;", "",
              "internal static class StopWordData", "{"]
    for name, code, ws in bodies:
        lines.append(f"    internal static readonly string[] {name.capitalize()} =")
        lines.append("    [")
        row = []
        for w in ws:
            row.append(literal(w) + ",")
            if len(row) == 8:
                lines.append("        " + " ".join(row))
                row = []
        if row:
            lines.append("        " + " ".join(row))
        lines.append("    ];")
        lines.append("")
    lines.append("    /// <summary>The sorted list for a language code, or null when no list is published.</summary>")
    lines.append("    internal static string[]? For(string language) => language switch")
    lines.append("    {")
    for name, code, _ in bodies:
        lines.append(f'        "{code}" => {name.capitalize()},')
    lines.append("        _ => null,")
    lines.append("    };")
    lines.append("}")
    dst.write_text("\n".join(lines) + "\n", encoding="utf-8")


main()
