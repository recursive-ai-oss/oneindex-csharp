using System.Text;

namespace OneIndex.Tools.SnowballGen;

/// <summary>
/// Emits a C# class for one Snowball script. Each Snowball command becomes straight-line C# that jumps to a label when the
/// command gives the signal f; the cursor is saved and restored by the construct that needs it (or, try, not, test, do, ...),
/// exactly as the manual describes them. A routine returns true when it falls off its end and false at its fail label.
/// </summary>
internal sealed class Emitter
{
    private sealed class Label(string name)
    {
        internal string Name { get; } = name;

        internal bool Used { get; set; }
    }

    private readonly Parser _parser;
    private readonly string _language;
    private readonly string _className;
    private readonly Dictionary<string, RoutineDef> _routines;
    private readonly List<(string Name, List<(string Text, int Group, int Routine)> Entries)> _tables = [];
    private readonly Dictionary<string, int> _amongRoutineIds = new(StringComparer.Ordinal);
    private StringBuilder _sb = new();
    private int _indent;
    private int _counter;
    private readonly HashSet<int> _substringVars = [];

    internal Emitter(Parser parser, string language)
    {
        _parser = parser;
        _language = language;
        _className = char.ToUpperInvariant(language[0]) + language[1..] + "Stemmer";
        _routines = parser.Routines.ToDictionary(r => r.Name, StringComparer.Ordinal);
    }

    internal string ClassName => _className;

    internal string Generate(string sourceName, string sourceVersion)
    {
        var methods = new StringBuilder();
        foreach (RoutineDef routine in _parser.Routines)
        {
            _sb = new StringBuilder();
            _indent = 2;
            _counter = 0;
            _substringVars.Clear();
            var fail = new Label("F");
            bool reachable = EmitCmd(routine.Body, routine.Backward, fail);
            string body = _sb.ToString();
            methods.AppendLine($"    private bool R_{routine.Name}()");
            methods.AppendLine("    {");
            foreach (int id in _substringVars.Order())
            {
                methods.AppendLine($"        int a{id} = 0;");
            }

            methods.Append(body);
            if (reachable)
            {
                methods.AppendLine("        return true;");
            }

            if (fail.Used)
            {
                methods.AppendLine("    F:");
                methods.AppendLine("        return false;");
            }

            methods.AppendLine("    }");
            methods.AppendLine();
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"// Generated by tools/SnowballGen from {sourceName} ({sourceVersion}). Do not edit.");
        sb.AppendLine("// The Snowball algorithm scripts are BSD-3-Clause, Copyright (c) 2001 Dr Martin Porter and (c) 2002 Richard Boulton;");
        sb.AppendLine("// see THIRD-PARTY-NOTICES.md.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace OneIndex.Analysis.Snowball;");
        sb.AppendLine();
        sb.AppendLine($"internal sealed class {_className} : SnowballProgram");
        sb.AppendLine("{");
        sb.AppendLine($"    public override string Language => \"{_language}\";");
        sb.AppendLine();
        foreach ((string name, string members) in _parser.Groupings)
        {
            sb.AppendLine($"    private static readonly Grouping G_{name} = new({Quote(members)});");
        }

        sb.AppendLine();
        foreach ((string name, List<(string Text, int Group, int Routine)> entries) in _tables)
        {
            sb.AppendLine($"    private static readonly AmongEntry[] {name} =");
            sb.AppendLine("    [");
            foreach ((string text, int group, int routine) in entries)
            {
                sb.AppendLine($"        new({Quote(text)}, {group}, {routine}),");
            }

            sb.AppendLine("    ];");
            sb.AppendLine();
        }

        foreach ((string name, NameKind kind) in _parser.Names.OrderBy(n => n.Key, StringComparer.Ordinal))
        {
            switch (kind)
            {
                case NameKind.Integer: sb.AppendLine($"    private int I_{name};"); break;
                case NameKind.Boolean: sb.AppendLine($"    private bool B_{name};"); break;
                case NameKind.String: sb.AppendLine($"    private readonly StringVariable S_{name} = new();"); break;
            }
        }

        sb.AppendLine();
        sb.AppendLine("    protected override bool Run() => R_stem();");
        sb.AppendLine();
        if (_amongRoutineIds.Count > 0)
        {
            sb.AppendLine("    protected override bool AmongRoutine(int routine) => routine switch");
            sb.AppendLine("    {");
            foreach ((string name, int id) in _amongRoutineIds.OrderBy(k => k.Value))
            {
                sb.AppendLine($"        {id} => R_{name}(),");
            }

            sb.AppendLine("        _ => true,");
            sb.AppendLine("    };");
            sb.AppendLine();
        }

        sb.Append(methods);
        sb.AppendLine("}");
        return sb.ToString().TrimEnd() + "\n";
    }

    // ----- output helpers -----

    private void Line(string text) => _sb.Append(' ', _indent * 4).AppendLine(text);

    private void Open() { Line("{"); _indent++; }

    private void Close() { _indent--; Line("}"); }

    private string Next(string prefix) => prefix + (++_counter);

    private Label NewLabel() => new(Next("L"));

    private void Goto(Label l)
    {
        l.Used = true;
        Line($"goto {l.Name};");
    }

    private void Place(Label l)
    {
        // Labels sit one level out so that they read as labels; a label always labels a statement.
        _sb.Append(' ', Math.Max(0, (_indent * 4) - 2)).AppendLine($"{l.Name}:");
    }

    private (bool Reachable, string Code) Capture(Func<bool> emit)
    {
        StringBuilder saved = _sb;
        _sb = new StringBuilder();
        bool reachable = emit();
        string code = _sb.ToString();
        _sb = saved;
        return (reachable, code);
    }

    private static string Quote(string s)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in s)
        {
            if (c == '"' || c == '\\')
            {
                sb.Append('\\').Append(c);
            }
            else if (c is >= ' ' and <= '~')
            {
                sb.Append(c);
            }
            else
            {
                sb.Append("\\u").Append(((int)c).ToString("X4", System.Globalization.CultureInfo.InvariantCulture));
            }
        }

        return sb.Append('"').ToString();
    }

    // Cursor save and restore. Edits happen to the right of the cursor going forward and to the left going backward, so the
    // forward code keeps the position and the backward code keeps the distance from the end of the text.
    private static string Save(bool back, string v) => back ? $"int {v} = Len - C;" : $"int {v} = C;";

    private static string Restore(bool back, string v) => back ? $"C = Len - {v};" : $"C = {v};";

    private static string Value(string? literal, string? variable) => literal is not null ? Quote(literal) : $"S_{variable}.Value";

    private static string Ex(Expr e, bool back) => e switch
    {
        Num n => n.Value.ToString(System.Globalization.CultureInfo.InvariantCulture),
        IntVar v => "I_" + v.Name,
        Special s => s.Which switch
        {
            "cursor" => "C",
            "limit" => back ? "Lb" : "L",
            "size" or "len" => "Len",
            "maxint" => "int.MaxValue",
            "minint" => "int.MinValue",
            _ => throw new InvalidDataException(s.Which),
        },
        SizeOf z => z.Literal is not null ? z.Literal.Length.ToString(System.Globalization.CultureInfo.InvariantCulture) : $"S_{z.Variable}.Length",
        Binary b => $"({Ex(b.Left, back)} {b.Op} {Ex(b.Right, back)})",
        Negate g => $"(-{Ex(g.Operand, back)})",
        _ => throw new InvalidDataException(e.ToString()),
    };

    // ----- commands -----

    /// <summary>Emits a command; returns whether the code after it can be reached.</summary>
    private bool EmitCmd(Cmd cmd, bool back, Label fail)
    {
        string dir = back ? "B" : string.Empty;
        switch (cmd)
        {
            case Seq seq:
                foreach (Cmd item in seq.Items)
                {
                    if (!EmitCmd(item, back, fail))
                    {
                        return false;
                    }
                }

                return true;
            case Literal lit:
                if (lit.Text.Length > 0)
                {
                    fail.Used = true;
                    Line($"if (!EqS{dir}({Quote(lit.Text)})) goto {fail.Name};");
                }

                return true;
            case StringTest st:
                fail.Used = true;
                Line($"if (!EqS{dir}(S_{st.Variable}.Value)) goto {fail.Name};");
                return true;
            case Call call:
                if (_routines[call.Routine].Backward != back)
                {
                    throw new InvalidDataException($"routine {call.Routine} is called in the wrong direction");
                }

                fail.Used = true;
                Line($"if (!R_{call.Routine}()) goto {fail.Name};");
                return true;
            case GroupTest g:
                fail.Used = true;
                Line($"if (!{(g.Negated ? "Out" : "In")}Grouping{dir}(G_{g.Grouping})) goto {fail.Name};");
                return true;
            case IntAssign a:
                Line($"I_{a.Variable} {a.Op} {Ex(a.Value, back)};");
                return true;
            case IntTest t:
                fail.Used = true;
                Line($"if (!({Ex(t.Left, back)} {t.Op} {Ex(t.Right, back)})) goto {fail.Name};");
                return true;
            case SetBool sb:
                Line($"B_{sb.Variable} = {(sb.Value ? "true" : "false")};");
                return true;
            case BoolTest bt:
                fail.Used = true;
                Line($"if (!B_{bt.Variable}) goto {fail.Name};");
                return true;
            case Simple s:
                return EmitSimple(s.Kind, back, fail);
            case HopCmd h:
                fail.Used = true;
                Line($"if (!Hop{dir}({Ex(h.Count, back)})) goto {fail.Name};");
                return true;
            case MarkCmd m:
                return EmitMark(m, back, fail);
            case SliceTo st:
                fail.Used = true;
                Line($"if (!SliceTo(S_{st.Variable})) goto {fail.Name};");
                return true;
            case SliceFrom sf:
                fail.Used = true;
                Line($"if (!SliceFrom({Value(sf.Literal, sf.Variable)})) goto {fail.Name};");
                return true;
            case InsertCmd ins:
                Line($"InsertS({Value(ins.Literal, ins.Variable)}, {(ins.Attach ? "true" : "false")}, {(back ? "true" : "false")});");
                return true;
            case Monadic mo:
                return EmitMonadic(mo, back, fail);
            case AndCmd andCmd:
                {
                    Open();
                    string v = Next("m");
                    Line(Save(back, v));
                    bool r = EmitCmd(andCmd.Left, back, fail);
                    if (r)
                    {
                        Line(Restore(back, v));
                        r = EmitCmd(andCmd.Right, back, fail);
                    }

                    Close();
                    return r;
                }

            case OrCmd orCmd:
                return EmitOr(orCmd, back, fail);
            case CountedCmd cc:
                return EmitCounted(cc, back, fail);
            case SetLimit sl:
                return EmitSetLimit(sl, back, fail);
            case Substring sub:
                {
                    string table = TableFor(sub.Among!);
                    _substringVars.Add(sub.Id);
                    fail.Used = true;
                    Line($"if ((a{sub.Id} = FindAmong{dir}({table})) == 0) goto {fail.Name};");
                    return true;
                }

            case Among among:
                return EmitAmong(among, back, fail);
            default:
                throw new InvalidDataException("cannot emit " + cmd);
        }
    }

    private bool EmitSimple(string kind, bool back, Label fail)
    {
        switch (kind)
        {
            case "true":
                return true;
            case "false":
                Goto(fail);
                return false;
            case "next":
                fail.Used = true;
                Line(back ? $"if (C <= Lb) goto {fail.Name};" : $"if (C >= L) goto {fail.Name};");
                Line(back ? "C--;" : "C++;");
                return true;
            case "[":
                Line(back ? "Ket = C;" : "Bra = C;");
                return true;
            case "]":
                Line(back ? "Bra = C;" : "Ket = C;");
                return true;
            case "delete":
                fail.Used = true;
                Line($"if (!SliceDel()) goto {fail.Name};");
                return true;
            case "tolimit":
                Line(back ? "C = Lb;" : "C = L;");
                return true;
            case "atlimit":
                fail.Used = true;
                Line(back ? $"if (C != Lb) goto {fail.Name};" : $"if (C != L) goto {fail.Name};");
                return true;
            default:
                throw new InvalidDataException(kind);
        }
    }

    private bool EmitMark(MarkCmd m, bool back, Label fail)
    {
        switch (m.Kind)
        {
            case "setmark":
                Line($"I_{m.Variable} = C;");
                return true;
            case "tomark":
                {
                    fail.Used = true;
                    string t = Next("t");
                    Open();
                    Line($"int {t} = {Ex(m.Value!, back)};");
                    Line(back ? $"if (C < {t} || Lb > {t}) goto {fail.Name};" : $"if (C > {t} || L < {t}) goto {fail.Name};");
                    Line($"C = {t};");
                    Close();
                    return true;
                }

            default:
                fail.Used = true;
                Line($"if (C != {Ex(m.Value!, back)}) goto {fail.Name};");
                return true;
        }
    }

    private bool EmitMonadic(Monadic mo, bool back, Label fail)
    {
        switch (mo.Kind)
        {
            case "reverse":
                return EmitCmd(mo.Operand, !back, fail);
            case "fail":
                {
                    bool r = EmitCmd(mo.Operand, back, fail);
                    if (r)
                    {
                        Goto(fail);
                    }

                    return false;
                }

            case "test":
                {
                    Open();
                    string v = Next("m");
                    Line(Save(back, v));
                    bool r = EmitCmd(mo.Operand, back, fail);
                    if (r)
                    {
                        Line(Restore(back, v));
                    }

                    Close();
                    return r;
                }

            case "not":
                {
                    var lf = NewLabel();
                    string v = Next("m");
                    (bool r, string code) = Capture(() => EmitCmd(mo.Operand, back, lf));
                    if (!lf.Used)
                    {
                        _sb.Append(code);
                        if (r)
                        {
                            Goto(fail);
                        }

                        return false;
                    }

                    Open();
                    Line(Save(back, v));
                    _sb.Append(code);
                    if (r)
                    {
                        Goto(fail);
                    }

                    Place(lf);
                    Line(Restore(back, v));
                    Close();
                    return true;
                }

            case "try":
                {
                    var lf = NewLabel();
                    var end = NewLabel();
                    string v = Next("m");
                    (bool r, string code) = Capture(() => EmitCmd(mo.Operand, back, lf));
                    if (!lf.Used)
                    {
                        _sb.Append(code);
                        return r;
                    }

                    Open();
                    Line(Save(back, v));
                    _sb.Append(code);
                    if (r)
                    {
                        Goto(end);
                    }

                    Place(lf);
                    Line(Restore(back, v));
                    if (r)
                    {
                        Place(end);
                        Line(";");
                    }

                    Close();
                    return true;
                }

            case "do":
                {
                    var lf = NewLabel();
                    string v = Next("m");
                    (bool r, string code) = Capture(() => EmitCmd(mo.Operand, back, lf));
                    Open();
                    Line(Save(back, v));
                    _sb.Append(code);
                    if (lf.Used)
                    {
                        Place(lf);
                    }

                    Line(Restore(back, v));
                    Close();
                    _ = r;
                    return true;
                }

            case "goto" or "gopast":
                return EmitSearch(mo, back, fail);
            case "repeat":
                {
                    var lf = NewLabel();
                    string v = Next("m");
                    (bool r, string code) = Capture(() => EmitCmd(mo.Operand, back, lf));
                    if (!lf.Used)
                    {
                        throw new InvalidDataException("repeat of a command that cannot fail never ends");
                    }

                    Line("for (;;)");
                    Open();
                    Line(Save(back, v));
                    _sb.Append(code);
                    if (r)
                    {
                        Line("continue;");
                    }

                    Place(lf);
                    Line(Restore(back, v));
                    Line("break;");
                    Close();
                    return true;
                }

            case "backwards":
                {
                    if (back)
                    {
                        throw new InvalidDataException("backwards cannot be nested");
                    }

                    string mc = Next("c"), mlb = Next("b");
                    var lf = NewLabel();
                    var end = NewLabel();
                    (bool r, string code) = Capture(() => EmitCmd(mo.Operand, true, lf));
                    Open();
                    Line($"int {mc} = C;");
                    Line($"int {mlb} = Lb;");
                    Line("Lb = C;");
                    Line("C = L;");
                    _sb.Append(code);
                    if (r)
                    {
                        Line($"C = {mc};");
                        Line($"Lb = {mlb};");
                        if (lf.Used)
                        {
                            Goto(end);
                        }
                    }

                    if (lf.Used)
                    {
                        Place(lf);
                        Line($"C = {mc};");
                        Line($"Lb = {mlb};");
                        Goto(fail);
                    }

                    if (r && lf.Used)
                    {
                        Place(end);
                        Line(";");
                    }

                    Close();
                    return r;
                }

            default:
                throw new InvalidDataException(mo.Kind);
        }
    }

    // goto C / gopast C: try C at the cursor, and if it fails move one character towards the limit and try again.
    private bool EmitSearch(Monadic mo, bool back, Label fail)
    {
        bool past = mo.Kind == "gopast";
        var lf = NewLabel();
        string v = Next("m");
        (bool r, string code) = Capture(() => EmitCmd(mo.Operand, back, lf));
        if (!lf.Used)
        {
            // C always succeeds, so goto leaves the cursor where it was and gopast after C.
            if (r)
            {
                Open();
                Line(Save(back, v));
                _sb.Append(code);
                if (!past)
                {
                    Line(Restore(back, v));
                }

                Close();
            }

            return r;
        }

        Line("for (;;)");
        Open();
        Line(Save(back, v));
        _sb.Append(code);
        if (r)
        {
            if (!past)
            {
                Line(Restore(back, v));
            }

            Line("break;");
        }

        Place(lf);
        Line(Restore(back, v));
        fail.Used = true;
        Line(back ? $"if (C <= Lb) goto {fail.Name};" : $"if (C >= L) goto {fail.Name};");
        Line(back ? "C--;" : "C++;");
        Close();
        return r;
    }

    private bool EmitOr(OrCmd orCmd, bool back, Label fail)
    {
        var lf = NewLabel();
        var end = NewLabel();
        string v = Next("m");
        (bool rl, string leftCode) = Capture(() => EmitCmd(orCmd.Left, back, lf));
        if (!lf.Used)
        {
            _sb.Append(leftCode);
            return rl;
        }

        Open();
        Line(Save(back, v));
        _sb.Append(leftCode);
        if (rl)
        {
            Goto(end);
        }

        Place(lf);
        Line(Restore(back, v));
        bool rr = EmitCmd(orCmd.Right, back, fail);
        if (rl)
        {
            Place(end);
            Line(";");
        }

        Close();
        return rl || rr;
    }

    private bool EmitCounted(CountedCmd cc, bool back, Label fail)
    {
        string n = Next("n");
        Open();
        Line($"int {n} = {Ex(cc.Count, back)};");
        Line($"while ({n}-- > 0)");
        Open();
        EmitCmd(cc.Operand, back, fail);
        Close();
        Close();
        if (cc.Kind == "atleast")
        {
            return EmitMonadic(new Monadic("repeat", cc.Operand), back, fail);
        }

        return true;
    }

    private bool EmitSetLimit(SetLimit sl, bool back, Label fail)
    {
        string mc = Next("c"), ml = Next("l"), mlen = Next("n");
        var lf = NewLabel();
        var end = NewLabel();
        Open();
        Line($"int {mc} = C;");
        bool r1 = EmitCmd(sl.Limit, back, fail);
        if (!r1)
        {
            Close();
            return false;
        }

        string limitVar = back ? "Lb" : "L";
        Line($"int {ml} = {limitVar};");
        if (!back)
        {
            Line($"int {mlen} = Len;");
        }

        Line($"{limitVar} = C;");
        Line($"C = {mc};");
        bool r2 = EmitCmd(sl.Body, back, lf);
        string restore = back ? $"{limitVar} = {ml};" : $"{limitVar} = {ml} + (Len - {mlen});";
        if (r2)
        {
            Line(restore);
            if (lf.Used)
            {
                Goto(end);
            }
        }

        if (lf.Used)
        {
            Place(lf);
            Line(restore);
            Goto(fail);
        }

        if (r2 && lf.Used)
        {
            Place(end);
            Line(";");
        }

        Close();
        return r2;
    }

    private bool EmitAmong(Among among, bool back, Label fail)
    {
        if (among.Starter is not null && !EmitCmd(among.Starter, back, fail))
        {
            return false;
        }

        Line($"switch (a{among.Sub!.Id})");
        Open();
        for (int g = 0; g < among.Groups.Count; g++)
        {
            Line($"case {g + 1}:");
            _indent++;
            bool r = true;
            if (among.Groups[g].Body is { } body)
            {
                Open();
                r = EmitCmd(body, back, fail);
                Close();
            }

            if (r)
            {
                Line("break;");
            }

            _indent--;
        }

        Close();
        return true;
    }

    private string TableFor(Among among)
    {
        string name = $"A_{among.Sub!.Id}";
        if (_tables.Any(t => t.Name == name))
        {
            return name;
        }

        var entries = new List<(string Text, int Group, int Routine)>();
        for (int g = 0; g < among.Groups.Count; g++)
        {
            foreach (AmongEntryDef e in among.Groups[g].Entries)
            {
                int routine = 0;
                if (e.Routine is not null)
                {
                    if (!_amongRoutineIds.TryGetValue(e.Routine, out routine))
                    {
                        routine = _amongRoutineIds.Count + 1;
                        _amongRoutineIds[e.Routine] = routine;
                    }
                }

                entries.Add((e.Text, g + 1, routine));
            }
        }

        // The longest matching string wins, so the search tries the longest first.
        _tables.Add((name, entries.Select((e, i) => (e, i)).OrderByDescending(x => x.e.Text.Length).ThenBy(x => x.i).Select(x => x.e).ToList()));
        return name;
    }
}
