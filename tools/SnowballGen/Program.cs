// Compiles Snowball algorithm scripts (algorithms/*.sbl) to C# stemmer classes.
//
//   dotnet run --project tools/SnowballGen -- <algorithms directory> <output directory> <version label> [language ...]
//
// The compiler is written from the Snowball manual (https://snowballstem.org/compiler/snowman.html). It reads only the scripts;
// no code from the Snowball project's compiler or its generated stemmers was consulted. Each language becomes
// <Name>Stemmer.g.cs, and one file registers them all.
using System.Text;

namespace OneIndex.Tools.SnowballGen;

internal static class Program
{
    private static readonly string[] DefaultLanguages =
    [
        "arabic", "armenian", "basque", "catalan", "czech", "danish", "dutch", "english", "esperanto", "estonian", "finnish", "french",
        "german", "greek", "hindi", "hungarian", "indonesian", "irish", "italian", "lithuanian", "nepali", "norwegian", "persian",
        "polish", "portuguese", "romanian", "russian", "serbian", "sesotho", "spanish", "swedish", "tamil", "turkish", "yiddish",
    ];

    private static int Main(string[] args)
    {
        if (args.Length < 3)
        {
            Console.Error.WriteLine("usage: SnowballGen <algorithms directory> <output directory> <version label> [language ...]");
            return 2;
        }

        string source = args[0];
        string output = args[1];
        string version = args[2];
        string[] languages = args.Length > 3 ? args[3..] : DefaultLanguages;
        Directory.CreateDirectory(output);

        var registry = new StringBuilder();
        registry.AppendLine("// <auto-generated>");
        registry.AppendLine("// Generated by tools/SnowballGen. Do not edit.");
        registry.AppendLine("// </auto-generated>");
        registry.AppendLine("#nullable enable");
        registry.AppendLine();
        registry.AppendLine("namespace OneIndex.Analysis.Snowball;");
        registry.AppendLine();
        registry.AppendLine("internal static class GeneratedStemmers");
        registry.AppendLine("{");
        registry.AppendLine($"    internal static readonly string[] Names = [{string.Join(", ", languages.Select(l => $"\"{l}\""))}];");
        registry.AppendLine();
        registry.AppendLine("    internal static Stemmer? Create(string language) => language switch");
        registry.AppendLine("    {");

        foreach (string language in languages)
        {
            string file = Path.Combine(source, language + ".sbl");
            byte[] bytes = File.ReadAllBytes(file);
            var lexer = new Lexer(Encoding.UTF8.GetString(bytes), language + ".sbl");
            var parser = new Parser(lexer.Tokenize(), language + ".sbl");
            parser.ParseProgram();
            var emitter = new Emitter(parser, language);
            File.WriteAllText(Path.Combine(output, emitter.ClassName + ".g.cs"), emitter.Generate($"algorithms/{language}.sbl", version), new UTF8Encoding(false));
            registry.AppendLine($"        \"{language}\" => new {emitter.ClassName}(),");
            Console.WriteLine($"{language}: {parser.Routines.Count} routines");
        }

        registry.AppendLine("        _ => null,");
        registry.AppendLine("    };");
        registry.AppendLine("}");
        File.WriteAllText(Path.Combine(output, "GeneratedStemmers.g.cs"), registry.ToString(), new UTF8Encoding(false));
        return 0;
    }
}
